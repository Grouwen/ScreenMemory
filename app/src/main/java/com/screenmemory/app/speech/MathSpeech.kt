package com.screenmemory.app.speech

/**
 * 数学网课语音识别的领域提示。
 *
 * 偏好词用于帮助识别引擎选出更可能的数学术语；normalize() 再兜底修正
 * 各引擎都可能出现的少量同音错误。这里只做高置信度替换，避免改动正常口语。
 */
object MathSpeech {

    val biasingTerms: List<String> = listOf(
        "约分", "通分", "平方根", "根号", "绝对值", "完全平方",
        "判别式", "定义域", "值域", "单调递增", "单调递减",
        "奇函数", "偶函数", "反函数", "对数函数", "指数函数",
        "三角函数", "正弦", "余弦", "正切", "通项公式", "递推公式",
        "等差数列", "等比数列", "公差", "公比", "数列",
        "因式分解", "配方法", "换元法", "待定系数法", "分类讨论",
        "韦达定理", "勾股定理", "导数", "极限", "积分", "向量",
        "坐标", "抛物线", "焦点", "准线", "不等式", "方程组",
        "分子", "分母", "分数", "整数", "有理数", "实数"
    )

    private val corrections = listOf(
        "约份" to "约分",
        "通份" to "通分",
        "判别是" to "判别式",
        "判別是" to "判别式",
        "定义玉" to "定义域",
        "值玉" to "值域",
        "单调递増" to "单调递增",
        "单调递減" to "单调递减",
        "单挑递增" to "单调递增",
        "单挑递减" to "单调递减",
        "奇涵数" to "奇函数",
        "偶涵数" to "偶函数",
        "反涵数" to "反函数",
        "对数涵数" to "对数函数",
        "指数涵数" to "指数函数",
        "三角涵数" to "三角函数",
        "正旋" to "正弦",
        "余旋" to "余弦",
        "通向公式" to "通项公式",
        "递推工式" to "递推公式",
        "等差数例" to "等差数列",
        "等比数例" to "等比数列",
        "换元发" to "换元法",
        "待定系数发" to "待定系数法",
        "分类讨伦" to "分类讨论",
        "伟大定理" to "韦达定理",
        "勾骨定理" to "勾股定理"
    )

    fun normalize(text: String): String {
        var result = text
        for ((wrong, correct) in corrections) {
            result = result.replace(wrong, correct)
        }
        return result
    }
}
